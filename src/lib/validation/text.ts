/**
 * 文字列入力の制御文字チェック（商品・取引先・在庫調整・受発注の備考で共通）。
 *
 * C0 制御（U+0000〜U+001F）・DEL（U+007F）・C1 制御（U+0080〜U+009F）に加えて、
 * 行区切り（U+2028・U+2029）、表示方向の制御（U+200E・U+200F・U+202A〜U+202E・U+2066〜U+2069）、
 * BOM（U+FEFF）を拒否する。表示方向の制御は見た目と実際の文字列をずらせるため、画面・CSV で紛らわしい。
 * DB やフレームワークに依存しない純粋なモジュール（クライアントからも import できる）
 */

/** 1 行の項目で使えない文字を含まない（改行・タブも不可） */
export const SINGLE_LINE =
  /^[^\u0000-\u001f\u007f-\u009f\u200e\u200f\u2028\u2029\u202a-\u202e\u2066-\u2069\ufeff]*$/;

/** 複数行の項目（備考）で使えない文字を含まない（改行 \n 以外の制御文字などは不可（タブも不可）。\r は呼び出し側で \n に揃える） */
export const MULTI_LINE =
  /^[^\u0000-\u0009\u000b-\u001f\u007f-\u009f\u200e\u200f\u2028\u2029\u202a-\u202e\u2066-\u2069\ufeff]*$/;

/** 1 行の項目のエラー文 */
export function singleLineMessage(label: string): string {
  return `${label}に改行・タブなどの制御文字は使えません`;
}
